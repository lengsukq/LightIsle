#!/usr/bin/env python3
"""Generate the same Fluid Surface palette for Web and native macOS.

Do not edit the generated files directly; edit design-tokens/tokens.json.
Use --check in CI to catch drift between the platforms.
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TOKENS = json.loads((ROOT / "design-tokens/tokens.json").read_text(encoding="utf-8"))
FLUID = TOKENS["fluid"]
COLORS = (
    "canvasTop", "canvasBottom", "cardTop", "cardBottom", "cardHover",
    "cardItemTop", "cardItemBottom", "chrome", "rim", "shadow"
)
CSS_NAMES = {
    "canvasTop": "canvas-top",
    "canvasBottom": "canvas-bottom",
    "cardTop": "card-top",
    "cardBottom": "card-bottom",
    "cardHover": "card-hover",
    "cardItemTop": "card-item-top",
    "cardItemBottom": "card-item-bottom",
    "chrome": "chrome",
    "rim": "rim",
    "shadow": "shadow",
}


def rgb(hex_color: str) -> tuple[int, int, int]:
    value = hex_color.removeprefix("#")
    if len(value) != 6:
        raise ValueError(f"Expected #RRGGBB: {hex_color}")
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def css_palette(mode: str) -> str:
    palette = FLUID[mode]
    lines = [f"  --fluid-{CSS_NAMES[key]}: {palette[key]};" for key in COLORS if key != "shadow"]
    lines.append("  --fluid-shadow-rgb: " + " ".join(map(str, rgb(palette["shadow"]))) + ";")
    lines.append(f'  --accent-primary: {TOKENS["color"][mode]["accentPrimary"]};')
    lines.append(f'  --accent-secondary: {TOKENS["color"][mode]["accentSecondary"]};')
    return "\n".join(lines)


motion = TOKENS["motion"]
radius = TOKENS["radiusPt"]
css = f"""/* Generated by scripts/sync-fluid-tokens.py — do not edit. */
:root {{
{css_palette("light")}
  --fluid-shadow-opacity: {FLUID["cardShadowOpacity"]};
  --fluid-shadow-radius: {FLUID["cardShadowRadius"]}px;
  --fluid-shadow-y: {FLUID["cardShadowY"]}px;
  --fluid-hover-shadow-opacity: {FLUID["hoverShadowOpacity"]};
  --fluid-hover-shadow-radius: {FLUID["hoverShadowRadius"]}px;
  --fluid-hover-shadow-y: {FLUID["hoverShadowY"]}px;
  --radius-xs: {radius["xs"]}px;
  --radius-sm: {radius["sm"]}px;
  --radius-md: {radius["md"]}px;
  --radius-lg: {radius["lg"]}px;
  --radius-xl: {radius["xl"]}px;
  --motion-fast: {motion["fastMs"]}ms;
  --motion-normal: {motion["normalMs"]}ms;
  --motion-spring: {motion["spring"]};
}}
[data-theme="dark"] {{
{css_palette("dark")}
}}
"""


def native_color(hex_color: str) -> str:
    values = rgb(hex_color)
    return "NSColor(srgbRed: " + ", green: ".join(
        [f"{value}.0 / 255.0" for value in values[:2]]
    ) + f", blue: {values[2]}.0 / 255.0, alpha: 1)"


def native_property(key: str) -> str:
    light = native_color(FLUID["light"][key])
    dark = native_color(FLUID["dark"][key])
    return f"""    static let {key} = Color(nsColor: NSColor(name: nil) {{ appearance in
        appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua
            ? {dark}
            : {light}
    }})
"""


swift = """// Generated by scripts/sync-fluid-tokens.py — do not edit.
import SwiftUI
import AppKit

enum IsleFluidPalette {
""" + "\n".join(native_property(key) for key in COLORS) + """
    static let accentPrimary = Color(nsColor: NSColor(name: nil) { appearance in
        appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua
            ? """ + native_color(TOKENS["color"]["dark"]["accentPrimary"]) + """
            : """ + native_color(TOKENS["color"]["light"]["accentPrimary"]) + """
    })
    static let accentSecondary = Color(nsColor: NSColor(name: nil) { appearance in
        appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua
            ? """ + native_color(TOKENS["color"]["dark"]["accentSecondary"]) + """
            : """ + native_color(TOKENS["color"]["light"]["accentSecondary"]) + """
    })
""" + f"""
    static let cardShadowOpacity: Double = {FLUID["cardShadowOpacity"]}
    static let cardShadowRadius: CGFloat = {FLUID["cardShadowRadius"]}
    static let cardShadowY: CGFloat = {FLUID["cardShadowY"]}
    static let hoverShadowOpacity: Double = {FLUID["hoverShadowOpacity"]}
    static let hoverShadowRadius: CGFloat = {FLUID["hoverShadowRadius"]}
    static let hoverShadowY: CGFloat = {FLUID["hoverShadowY"]}
    static let cardRadius: CGFloat = {radius["lg"]}
    static let heroRadius: CGFloat = {radius["xl"]}
    static let itemRadius: CGFloat = {radius["md"]}
    static let smRadius: CGFloat = {radius["sm"]}
}}
"""

outputs = {
    ROOT / "apps/web/src/generated-fluid.css": css,
    ROOT / "apps/macos/Sources/LightIsle/IsleFluidPalette.swift": swift,
}
checking = "--check" in sys.argv
failed = []
for filename, expected in outputs.items():
    if checking:
        if not filename.exists() or filename.read_text(encoding="utf-8") != expected:
            failed.append(str(filename.relative_to(ROOT)))
    else:
        filename.write_text(expected, encoding="utf-8")
if failed:
    sys.exit("Fluid design tokens are out of sync: " + ", ".join(failed))
print("Fluid tokens verified." if checking else "Fluid tokens generated for Web and macOS.")

#!/usr/bin/env python3
"""Generate Flutter semantic palette from the same tokens as Mac and Web."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
tokens = json.loads((root / 'design-tokens/tokens.json').read_text())
output = root / 'apps/flutter/lib/core/generated_isle_tokens.dart'
lines = ['// Generated by scripts/sync-flutter-tokens.py; edit design-tokens/tokens.json.', "import 'package:flutter/material.dart';", '', 'abstract final class IsleTokens {']
for group in ['color', 'fluid']:
    for mode in ['light', 'dark']:
        lines.append(f'  static const {group}{mode.title()} = <String, Color>{{')
        for name, value in tokens[group][mode].items():
            if isinstance(value, str) and value.startswith('#'):
                lines.append(f"    '{name}': Color(0xff{value[1:].lower()}),")
        lines.append('  };')
for mode in ['light', 'dark']:
    # Shared Mac/Flutter surfaces must come from the *same* nativeMac
    # semantic source; do not hand-copy rounded-corner and palette values.
    lines.append(f'  static const native{mode.title()} = <String, Color>{{')
    for name, value in tokens['nativeMac'][mode].items():
        if isinstance(value, str) and value.startswith('#'):
            lines.append(f"    '{name}': Color(0xff{value[1:].lower()}),")
    lines.append('  };')
native_surface = tokens['nativeMac']['surface']
lines += [
    f'  static const cardRadius = {float(native_surface["cardRadius"])};',
    f'  static const heroRadius = {float(native_surface["heroRadius"])};',
    f'  static const itemRadius = {float(native_surface["itemRadius"])};',
    f'  static const controlRadius = {float(native_surface["controlRadius"])};',
    '}',''
]
expected = '\n'.join(lines)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not output.exists() or output.read_text() != expected:
        raise SystemExit('Flutter design tokens need regeneration: python3 scripts/sync-flutter-tokens.py')
    print('Flutter tokens match shared Web/macOS source.')
else:
    output.write_text(expected)
